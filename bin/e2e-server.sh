#!/usr/bin/env bash
#
# SH Speed Optimizer - PHP built-in web server for the E2E WordPress site.
#
# Usage: bin/e2e-server.sh start|stop|restart|status
#
# Environment:
#   SHSO_E2E_DIR             WordPress root (default /home/user/shso-e2e/wordpress)
#   SHSO_E2E_PORT            Port           (default 8889)
#   PHP_CLI_SERVER_WORKERS   Worker processes (default 8). The plugin makes
#                            loopback HTTP requests to its own site while
#                            handling a request, so more than one worker is
#                            required or those requests deadlock.
#
# Files (next to the WordPress directory):
#   router.php  server.pid  server.log
#
set -euo pipefail

SHSO_E2E_DIR="${SHSO_E2E_DIR:-/home/user/shso-e2e/wordpress}"
SHSO_E2E_PORT="${SHSO_E2E_PORT:-8889}"
export PHP_CLI_SERVER_WORKERS="${PHP_CLI_SERVER_WORKERS:-8}"

[ -d "$SHSO_E2E_DIR" ] || { echo "[e2e-server] $SHSO_E2E_DIR does not exist - run bin/e2e-setup.sh first." >&2; exit 1; }
SHSO_E2E_DIR="$(cd "$SHSO_E2E_DIR" && pwd -P)"
E2E_ROOT="$(dirname "$SHSO_E2E_DIR")"
ROUTER="$E2E_ROOT/router.php"
PID_FILE="$E2E_ROOT/server.pid"
LOG_FILE="$E2E_ROOT/server.log"
HOST="127.0.0.1"
URL="http://${HOST}:${SHSO_E2E_PORT}"

# Loopback requests (WordPress -> itself) must never go through a proxy.
export no_proxy="127.0.0.1,localhost${no_proxy:+,$no_proxy}"
export NO_PROXY="127.0.0.1,localhost${NO_PROXY:+,$NO_PROXY}"

log() { printf '[e2e-server] %s\n' "$*"; }

write_router() {
	cat > "$ROUTER" <<'PHP'
<?php
/**
 * Router for the PHP built-in web server (generated by bin/e2e-server.sh).
 *
 * - existing static files are served directly by the server,
 * - existing *.php files (wp-login.php, wp-admin/*.php, ...) are executed by the
 *   server itself so SCRIPT_NAME / PHP_SELF stay correct for wp-admin,
 * - directories with an index.php (/, /wp-admin/) are served by the server,
 * - everything else (pretty permalinks, /wp-json/...) goes to WordPress' index.php.
 */
$root = rtrim( $_SERVER['DOCUMENT_ROOT'], '/' );
$path = '/' . ltrim( rawurldecode( (string) parse_url( $_SERVER['REQUEST_URI'], PHP_URL_PATH ) ), '/' );

// Never expose the SQLite database, dotfiles, wp-config.php or logs.
if ( preg_match( '~/\.(?!well-known/)|/wp-config\.php$|\.log$~i', $path ) ) {
	http_response_code( 403 );
	echo 'Forbidden';
	return true;
}

$file = $root . $path;

if ( is_file( $file ) ) {
	return false;
}

if ( is_dir( $file ) ) {
	if ( '/' !== substr( $path, -1 ) ) {
		$qs = isset( $_SERVER['QUERY_STRING'] ) && '' !== $_SERVER['QUERY_STRING'] ? '?' . $_SERVER['QUERY_STRING'] : '';
		header( 'Location: ' . $path . '/' . $qs, true, 301 );
		return true;
	}
	if ( is_file( $file . 'index.php' ) || is_file( $file . 'index.html' ) ) {
		return false;
	}
}

// PATH_INFO style requests to an existing script, e.g. /index.php/wp-json/...
if ( preg_match( '~^(.+?\.php)(/.*)$~i', $path, $m ) && is_file( $root . $m[1] ) ) {
	return false;
}

// Front controller (behaves like Apache mod_rewrite / nginx try_files).
unset( $_SERVER['PATH_INFO'], $_SERVER['ORIG_PATH_INFO'] );
$_SERVER['SCRIPT_NAME']     = '/index.php';
$_SERVER['PHP_SELF']        = '/index.php';
$_SERVER['SCRIPT_FILENAME'] = $root . '/index.php';
chdir( $root );
require $root . '/index.php';
PHP
}

read_pid() { [ -f "$PID_FILE" ] && cat "$PID_FILE" 2>/dev/null || true; }

is_running() {
	local pid
	pid="$(read_pid)"
	[ -n "$pid" ] && kill -0 "$pid" 2>/dev/null
}

http_code() { curl -s -o /dev/null --max-time 30 -w '%{http_code}' "$URL/" 2>/dev/null || true; }

wait_ready() {
	local i code=""
	for i in $(seq 1 120); do
		code="$(http_code)"
		if [ "$code" = "200" ]; then return 0; fi
		if ! is_running; then
			log "Server process died. Last log lines:"
			tail -n 20 "$LOG_FILE" >&2 || true
			return 1
		fi
		sleep 0.5
	done
	log "Timed out waiting for HTTP 200 on $URL/ (last status: ${code:-none})."
	return 1
}

start() {
	if is_running; then
		log "Already running (pid $(read_pid)) on $URL"
		wait_ready
		return
	fi
	if [ "$(curl -s -o /dev/null --max-time 5 -w '%{http_code}' "$URL/" 2>/dev/null || true)" != "000" ]; then
		log "Port $SHSO_E2E_PORT is already in use by another process." >&2
		exit 1
	fi
	[ -f "$SHSO_E2E_DIR/wp-config.php" ] || { log "No wp-config.php in $SHSO_E2E_DIR - run bin/e2e-setup.sh first." >&2; exit 1; }
	write_router
	log "Starting PHP $(php -r 'echo PHP_VERSION;') built-in server on $URL with $PHP_CLI_SERVER_WORKERS workers"
	{ echo; echo "=== $(date '+%Y-%m-%d %H:%M:%S') start (workers=$PHP_CLI_SERVER_WORKERS) ==="; } >> "$LOG_FILE"
	# setsid: own process group, so stop can terminate the master and all workers.
	nohup setsid php \
		-d memory_limit=512M \
		-d max_execution_time=300 \
		-d output_buffering=4096 \
		-d display_errors=0 \
		-d log_errors=1 \
		-d upload_max_filesize=64M \
		-d post_max_size=64M \
		-d opcache.enable_cli=1 \
		-d opcache.validate_timestamps=1 \
		-d opcache.revalidate_freq=0 \
		-S "${HOST}:${SHSO_E2E_PORT}" -t "$SHSO_E2E_DIR" "$ROUTER" \
		>> "$LOG_FILE" 2>&1 < /dev/null &
	echo $! > "$PID_FILE"
	if wait_ready; then
		log "Ready: $URL (pid $(read_pid), log $LOG_FILE)"
	else
		stop || true
		exit 1
	fi
}

stop() {
	local pid i
	pid="$(read_pid)"
	if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null; then
		log "Stopping server (pid $pid)"
		kill -TERM -- "-$pid" 2>/dev/null || kill -TERM "$pid" 2>/dev/null || true
		for i in $(seq 1 20); do
			kill -0 "$pid" 2>/dev/null || break
			sleep 0.25
		done
		kill -KILL -- "-$pid" 2>/dev/null || true
	else
		log "Not running"
	fi
	# Stray workers (e.g. pid file lost).
	pkill -f -- "-S ${HOST}:${SHSO_E2E_PORT} " 2>/dev/null || true
	rm -f "$PID_FILE"
}

status() {
	local code
	code="$(http_code)"
	if is_running; then
		log "Running (pid $(read_pid), workers $(pgrep -f -- "-S ${HOST}:${SHSO_E2E_PORT} " | wc -l | tr -d ' ') processes) on $URL - GET / -> HTTP $code"
		log "Docroot $SHSO_E2E_DIR, log $LOG_FILE"
		[ "$code" = "200" ]
	else
		log "Not running (GET $URL/ -> HTTP $code)"
		return 3
	fi
}

case "${1:-}" in
	start) start ;;
	stop) stop ;;
	restart) stop; start ;;
	status) status ;;
	*) echo "Usage: $0 start|stop|restart|status" >&2; exit 2 ;;
esac
